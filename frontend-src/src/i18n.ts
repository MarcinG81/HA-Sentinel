export type I18nKey = Key;
export type Translate = (key: string) => string;

export function translator(language: string | undefined): Translate {
  const dict: Record<string, string> = (language ?? "").toLowerCase().startsWith("pl") ? pl : en;
  return (key: string) => dict[key] ?? (en as Record<string, string>)[key] ?? key;
}

/** Date in the HA time zone; details show the UTC offset (spec 14.2). */
export function formatDate(iso: string | null, language: string, timeZone: string, withOffset = false): string {
  if (!iso) return "—";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "—";
  const fmt = new Intl.DateTimeFormat(language, {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    ...(withOffset ? { timeZoneName: "shortOffset" } : {}),
  });
  return fmt.format(d);
}
